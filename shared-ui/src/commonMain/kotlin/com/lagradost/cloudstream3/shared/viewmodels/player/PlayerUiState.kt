/**
 * Quality track available for playback in the player.
 */
@Serializable
data class PlayerQuality(
    val id: String = "",
    val name: String = "",
    val quality: Int = 0,
    val url: String = "",
    val headers: Map<String, String> = emptyMap(),
    val isAuto: Boolean = false,
    @Transient val extractorLink: ExtractorLink? = null
) {
    /**
     * Effective numerical resolution in pixels (e.g. 2160, 1440, 1080, 720, 480, 360, 240, 144)
     * used for deterministic sorting and automatic selection of optimal quality.
     */
    val effectiveResolution: Int
        get() {
            if (quality > 0 && quality != Qualities.Unknown.value) {
                return quality
            }
            val text = "$name $id".lowercase()
            return when {
                "2160" in text || "4k" in text || "uhd" in text -> 2160
                "1440" in text || "2k" in text || "qhd" in text -> 1440
                "1080" in text || "fhd" in text -> 1080
                "720" in text || "hd" in text -> 720
                "480" in text || "sd" in text -> 480
                "360" in text -> 360
                "240" in text -> 240
                "144" in text -> 144
                quality == Qualities.Unknown.value -> 1
                isAuto || quality == 0 -> 0
                else -> quality
            }
        }

    companion object {
        val Auto = PlayerQuality(id = "auto", name = "Auto", quality = 0, url = "", isAuto = true)

        fun fromExtractorLink(link: ExtractorLink): PlayerQuality {
            val allHeaders = mutableMapOf<String, String>()
            if (link.referer.isNotBlank()) {
                allHeaders["Referer"] = link.referer
            }
            allHeaders.putAll(link.headers)
            return PlayerQuality(
                id = "${link.source}_${link.name}_${link.quality}",
                name = link.name,
                quality = link.quality,
                url = link.url,
                headers = allHeaders,
                isAuto = link.quality == 0,
                extractorLink = link
            )
        }
    }
}

/**
 * Subtitle track available for the media.
 */
@Serializable
data class PlayerSubtitleTrack(
    val id: String = "",
    val name: String = "",
    val languageCode: String? = null,
    val url: String = "",
    val headers: Map<String, String> = emptyMap(),
    val isAutoGenerated: Boolean = false,
    val isDefault: Boolean = false,
    @Transient val subtitleFile: SubtitleFile? = null
) {
    companion object {
        fun fromSubtitleFile(file: SubtitleFile, isDefault: Boolean = false): PlayerSubtitleTrack {
            return PlayerSubtitleTrack(
                id = file.url,
                name = file.lang,
                languageCode = file.langTag,
                url = file.url,
                headers = file.headers ?: emptyMap(),
                isAutoGenerated = false,
                isDefault = isDefault,
                subtitleFile = file
            )
        }
    }
}

/**
 * Type of skip segment (opening, ending, recap, etc.).
 */
enum class PlayerSkipType {
    Opening,
    Ending,
    Recap,
    MixedOpening,
    MixedEnding,
    Credits,
    Intro,
    Preview,
    Custom
}

/**
 * Timestamp marker for skipping intro/outro/recap/credits in video playback.
 */
@Serializable
data class PlayerSkipTimestamp(
    val type: PlayerSkipType = PlayerSkipType.Intro,
    val startMs: Long,
    val endMs: Long,
    val label: String? = null
) {
    val isIntro: Boolean
        get() = type == PlayerSkipType.Opening ||
                type == PlayerSkipType.Intro ||
                type == PlayerSkipType.Recap ||
                type == PlayerSkipType.MixedOpening

    val isOutro: Boolean
        get() = type == PlayerSkipType.Ending ||
                type == PlayerSkipType.Credits ||
                type == PlayerSkipType.MixedEnding ||
                type == PlayerSkipType.Preview

    fun contains(posMs: Long): Boolean = posMs in startMs..endMs
}


