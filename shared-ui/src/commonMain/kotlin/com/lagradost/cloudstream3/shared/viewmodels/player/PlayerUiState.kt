/**
 * Immutable UI state for the video player controller (MVI pattern).
 */
data class PlayerUiState(
    val isPlaying: Boolean = false,
    val isBuffering: Boolean = false,
    val isStopped: Boolean = true,
    val positionMs: Long = 0L,
    val durationMs: Long = 0L,
    val currentUrl: String? = null,
    val availableQualities: List<PlayerQuality> = emptyList(),
    val selectedQuality: PlayerQuality? = null,
    val availableSubtitles: List<PlayerSubtitleTrack> = emptyList(),
    val selectedSubtitle: PlayerSubtitleTrack? = null,
    val availableAudioTracks: List<PlayerAudioTrack> = emptyList(),
    val selectedAudioTrack: PlayerAudioTrack? = null,
    val playbackSpeed: Float = 1.0f,
    val aspectRatio: PlayerAspectRatio = PlayerAspectRatio.Fit,
    val subtitleDelayMs: Long = 0L,
    val audioDelayMs: Long = 0L,
    val areControlsVisible: Boolean = true,
    val activeModal: PlayerActiveModal? = null,
    val isControlsLocked: Boolean = false,
    val lockPin: String? = null,
    val isPinLocked: Boolean = false,
    val showLockPinDialog: Boolean = false,
    val lockPinDialogMode: LockPinDialogMode = LockPinDialogMode.Unlock,
    val skipTimestamps: List<PlayerSkipTimestamp> = emptyList(),
    val activeSkipTimestamp: PlayerSkipTimestamp? = null,
    val accountId: Int = 0,
    val parentId: Int? = null,
    val currentEpisodeId: Int? = null,
    val currentEpisode: PlayerEpisode? = null,
    val playlist: List<PlayerEpisode> = emptyList(),
    val currentEpisodeIndex: Int = 0,
    val hasNextEpisode: Boolean = false,
    val hasPreviousEpisode: Boolean = false,
    val errorMessage: String? = null
) : UiState {
    val progressPercentage: Float
        get() = if (durationMs > 0L) (positionMs.toFloat() / durationMs.toFloat()).coerceIn(0f, 1f) else 0f

    val formattedPosition: String
        get() = formatTime(positionMs)

    val formattedDuration: String
        get() = formatTime(durationMs)

    companion object {
        fun formatTime(millis: Long): String {
            val totalSeconds = (millis / 1000).coerceAtLeast(0)
            val seconds = totalSeconds % 60
            val minutes = (totalSeconds / 60) % 60
            val hours = totalSeconds / 3600
            return if (hours > 0) {
                "${hours}:${minutes.toString().padStart(2, '0')}:${seconds.toString().padStart(2, '0')}"
            } else {
                "${minutes}:${seconds.toString().padStart(2, '0')}"
            }
        }
    }
}
