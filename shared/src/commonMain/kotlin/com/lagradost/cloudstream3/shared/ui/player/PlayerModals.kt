@Composable
private fun SubtitleListContent(
    subtitles: List<PlayerSubtitleTrack>,
    selectedSubtitle: PlayerSubtitleTrack?,
    isSearching: Boolean,
    onSelect: (PlayerSubtitleTrack) -> Unit,
    modifier: Modifier = Modifier
) {
    if (subtitles.isEmpty() && isSearching) {
        Box(
            modifier = modifier
                .fillMaxWidth()
                .padding(vertical = 16.dp),
            contentAlignment = Alignment.Center
        ) {
            BodyMutedText(text = stringResource(Res.string.no_subtitles_loaded))
        }
    } else if (subtitles.isNotEmpty()) {
        LazyColumn(
            verticalArrangement = Arrangement.spacedBy(8.dp),
            modifier = modifier
                .fillMaxWidth()
                .heightIn(max = 300.dp)
        ) {
            items(subtitles) { subtitle ->
                val isSelected = subtitle == selectedSubtitle || subtitle.id == selectedSubtitle?.id
                SubtitleOptionCard(
                    track = subtitle,
                    isSelected = isSelected,
                    onClick = { onSelect(subtitle) }
                )
            }
        }
    }
}

@Composable
private fun SubtitleOptionCard(
    track: PlayerSubtitleTrack,
    isSelected: Boolean,
    onClick: () -> Unit,
    modifier: Modifier = Modifier
) {
    val onlineLabel = stringResource(Res.string.subtitles_from_online)
    val embeddedLabel = stringResource(Res.string.subtitles_from_embedded)
    val description = resolveSubtitleDescription(track, onlineLabel, embeddedLabel)

    SelectableOptionCard(
        isSelected = isSelected,
        title = track.name,
        subtitle = description,
        accentColor = CloudStreamColors.Secondary,
        onClick = onClick,
        modifier = modifier
    )
}

