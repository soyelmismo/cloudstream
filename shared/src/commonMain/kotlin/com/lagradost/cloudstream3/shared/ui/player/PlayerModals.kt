private val SPEED_OPTIONS = listOf(0.5f, 0.75f, 1.0f, 1.25f, 1.5f, 1.75f, 2.0f)

private fun resolveQualityBadgeColor(effectiveRes: Int): Color = when {
    effectiveRes >= 2160 -> CloudStreamColors.Quality4K
    effectiveRes >= 1080 -> CloudStreamColors.QualityHD
    effectiveRes >= 720 -> CloudStreamColors.QualityHQ
    else -> CloudStreamColors.QualitySD
}

private fun filterSubtitles(
    subtitles: ImmutableList<PlayerSubtitleTrack>,
    query: String
): List<PlayerSubtitleTrack> {
    if (query.isBlank()) return subtitles
    return subtitles.filter { track ->
        track.name.contains(query, ignoreCase = true) ||
                track.languageCode?.contains(query, ignoreCase = true) == true
    }
}

private fun resolveSubtitleDescription(
    track: PlayerSubtitleTrack,
    onlineLabel: String,
    embeddedLabel: String
): String {
    track.languageCode?.takeIf { it.isNotBlank() }?.let { return it }
    return if (track.isAutoGenerated) onlineLabel else embeddedLabel
}

private fun filterEpisodes(
    playlist: ImmutableList<PlayerEpisode>,
    query: String
): List<IndexedValue<PlayerEpisode>> {
    val indexedList = playlist.withIndex().toList()
    if (query.isBlank()) return indexedList
    return indexedList.filter { (_, ep) ->
        val epName = ep.name.orEmpty()
        val epNum = ep.episodeNumber?.toString().orEmpty()
        epName.contains(query, ignoreCase = true) || epNum.contains(query)
    }
}

private fun resolveEpisodeSubtitle(
    ep: PlayerEpisode,
    seasonShort: String,
    episodeShort: String
): String {
    return buildString {
        if (ep.seasonNumber != null && ep.seasonNumber > 0) {
            append("$seasonShort${ep.seasonNumber} ")
        }
        if (ep.episodeNumber != null) {
            append("$episodeShort${ep.episodeNumber}")
        }
    }
}

private fun resolveAspectRatioStrings(ratio: PlayerAspectRatio): Pair<StringResource, StringResource> {
    return when (ratio) {
        PlayerAspectRatio.Fit -> Res.string.aspect_ratio_fit to Res.string.aspect_ratio_fit
        PlayerAspectRatio.Zoom -> Res.string.aspect_ratio_zoom to Res.string.aspect_ratio_zoom
        PlayerAspectRatio.Stretch -> Res.string.aspect_ratio_stretch to Res.string.aspect_ratio_stretch
        PlayerAspectRatio.Original -> Res.string.aspect_ratio_original to Res.string.aspect_ratio_original
    }
}

@Composable
fun PlayerQualitySourcesModal(
    state: PlayerUiState,
    onEvent: (PlayerUiEvent) -> Unit,
    onDismiss: () -> Unit = { onEvent(PlayerUiEvent.SetActiveModal(null)) }
) {
    ActionDialog(
        onDismissRequest = onDismiss,
        titleRes = Res.string.video_quality,
        icon = {
            Icon(
                painter = painterResource(Res.drawable.ic_baseline_hd_24),
                contentDescription = stringResource(Res.string.quality),
                tint = CloudStreamColors.Primary,
                modifier = Modifier.size(24.dp)
            )
        },
        showCloseButton = true,
        confirmTextRes = Res.string.close,
        onConfirm = onDismiss,
        content = {
            if (state.availableQualities.isEmpty()) {
                Box(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(vertical = 24.dp),
                    contentAlignment = Alignment.Center
                ) {
                    BodyMutedText(text = stringResource(Res.string.no_qualities_available))
                }
            } else {
                LazyColumn(
                    verticalArrangement = Arrangement.spacedBy(8.dp),
                    modifier = Modifier
                        .fillMaxWidth()
                        .heightIn(max = 340.dp)
                ) {
                    items(state.availableQualities) { quality ->
                        val isSelected = quality.url == state.currentUrl ||
                                quality == state.selectedQuality ||
                                quality.id == state.selectedQuality?.id ||
                                (quality.isAuto && state.selectedQuality == null)

                        QualityOptionCard(
                            quality = quality,
                            isSelected = isSelected,
                            onClick = {
                                onEvent(PlayerUiEvent.SelectQuality(quality))
                                onEvent(PlayerUiEvent.SetActiveModal(null))
                            }
                        )
                    }
                }
            }
        }
    )
}

@Composable
private fun QualityOptionCard(
    quality: PlayerQuality,
    isSelected: Boolean,
    onClick: () -> Unit,
    modifier: Modifier = Modifier
) {
    val effectiveRes = quality.effectiveResolution
    val badgeColor = resolveQualityBadgeColor(effectiveRes)
    val qualityLabel = if (effectiveRes > 1) "${effectiveRes}p" else stringResource(Res.string.quality_auto)

    SelectableOptionCard(
        isSelected = isSelected,
        title = quality.name.ifBlank { qualityLabel },
        leadingContent = {
            MediaBadge(
                text = qualityLabel,
                backgroundColor = badgeColor,
                textColor = CloudStreamColors.OnMediaScrim
            )
        },
        onClick = onClick,
        modifier = modifier
    )
}

@Composable
fun PlayerSubtitlesModal(
    state: PlayerUiState,
    onEvent: (PlayerUiEvent) -> Unit,
    onDismiss: () -> Unit = { onEvent(PlayerUiEvent.SetActiveModal(null)) }
) {
    var searchQuery by remember { mutableStateOf("") }
    val filteredSubtitles = remember(state.availableSubtitles, searchQuery) {
        filterSubtitles(state.availableSubtitles, searchQuery)
    }

    ActionDialog(
        onDismissRequest = onDismiss,
        titleRes = Res.string.subtitles,
        icon = {
            Icon(
                painter = painterResource(Res.drawable.ic_outline_subtitles_24),
                contentDescription = stringResource(Res.string.subtitles),
                tint = CloudStreamColors.Secondary,
                modifier = Modifier.size(24.dp)
            )
        },
        showCloseButton = true,
        confirmTextRes = Res.string.close,
        onConfirm = onDismiss,
        content = {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .heightIn(max = 380.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                if (state.availableSubtitles.size > 5) {
                    CloudStreamTextField(
                        value = searchQuery,
                        onValueChange = { searchQuery = it },
                        placeholder = stringResource(Res.string.search),
                        leadingIconVector = Icons.Default.Search,
                        singleLine = true,
                        modifier = Modifier.fillMaxWidth()
                    )
                }

                if (searchQuery.isBlank()) {
                    SubtitleOffOptionCard(
                        isSelected = state.selectedSubtitle == null,
                        onClick = {
                            onEvent(PlayerUiEvent.SelectSubtitle(null))
                            onEvent(PlayerUiEvent.SetActiveModal(null))
                        }
                    )
                }

                SubtitleListContent(
                    subtitles = filteredSubtitles,
                    selectedSubtitle = state.selectedSubtitle,
                    isSearching = searchQuery.isNotBlank(),
                    onSelect = { subtitle ->
                        onEvent(PlayerUiEvent.SelectSubtitle(subtitle))
                        onEvent(PlayerUiEvent.SetActiveModal(null))
                    }
                )
            }
        }
    )
}

