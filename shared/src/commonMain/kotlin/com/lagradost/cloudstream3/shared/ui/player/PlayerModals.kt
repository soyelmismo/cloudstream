@Composable
fun PlayerActiveModals(
    state: PlayerUiState,
    onEvent: (PlayerUiEvent) -> Unit,
    onDismiss: () -> Unit = { onEvent(PlayerUiEvent.SetActiveModal(null)) }
) {
    val modal = state.activeModal ?: return
    if (renderMediaSelectionModal(modal, state, onEvent, onDismiss)) return
    renderPlaybackSettingsModal(modal, state, onEvent, onDismiss)
}

@Composable
private fun renderMediaSelectionModal(
    modal: PlayerActiveModal,
    state: PlayerUiState,
    onEvent: (PlayerUiEvent) -> Unit,
    onDismiss: () -> Unit
): Boolean {
    when (modal) {
        PlayerActiveModal.QUALITY_SOURCES -> PlayerQualitySourcesModal(state, onEvent, onDismiss)
        PlayerActiveModal.SUBTITLES -> PlayerSubtitlesModal(state, onEvent, onDismiss)
        PlayerActiveModal.AUDIO_TRACKS -> PlayerAudioTracksModal(state, onEvent, onDismiss)
        else -> return false
    }
    return true
}

@Composable
private fun renderPlaybackSettingsModal(
    modal: PlayerActiveModal,
    state: PlayerUiState,
    onEvent: (PlayerUiEvent) -> Unit,
    onDismiss: () -> Unit
) {
    when (modal) {
        PlayerActiveModal.SPEED -> PlayerSpeedModal(state, onEvent, onDismiss)
        PlayerActiveModal.EPISODES -> PlayerEpisodesModal(state, onEvent, onDismiss)
        PlayerActiveModal.SETTINGS -> PlayerAspectRatioModal(state, onEvent, onDismiss)
        else -> Unit
    }
}

