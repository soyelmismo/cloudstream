@Composable
fun PlayerEpisodesModal(
    state: PlayerUiState,
    onEvent: (PlayerUiEvent) -> Unit,
    onDismiss: () -> Unit = { onEvent(PlayerUiEvent.SetActiveModal(null)) }
) {
    var searchQuery by remember { mutableStateOf("") }
    val filteredPlaylist = remember(state.playlist, searchQuery) {
        filterEpisodes(state.playlist, searchQuery)
    }
    val listState = rememberLazyListState()

    LaunchedEffect(state.currentEpisodeIndex) {
        if (state.currentEpisodeIndex in state.playlist.indices) {
            val targetIndex = filteredPlaylist.indexOfFirst { it.index == state.currentEpisodeIndex }
            if (targetIndex >= 0) {
                listState.animateScrollToItem(targetIndex)
            }
        }
    }

    ActionDialog(
        onDismissRequest = onDismiss,
        titleRes = Res.string.episodes,
        iconVector = Icons.Default.VideoLibrary,
        showCloseButton = true,
        confirmTextRes = Res.string.close,
        onConfirm = onDismiss,
        content = {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .heightIn(max = 380.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                if (state.playlist.size > 5) {
                    CloudStreamTextField(
                        value = searchQuery,
                        onValueChange = { searchQuery = it },
                        placeholder = stringResource(Res.string.search_episodes_hint),
                        leadingIconVector = Icons.Default.Search,
                        singleLine = true,
                        modifier = Modifier.fillMaxWidth()
                    )
                }

                if (filteredPlaylist.isEmpty()) {
                    Box(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(24.dp),
                        contentAlignment = Alignment.Center
                    ) {
                        BodyMutedText(text = stringResource(Res.string.no_episodes_available))
                    }
                } else {
                    LazyColumn(
                        state = listState,
                        verticalArrangement = Arrangement.spacedBy(8.dp),
                        modifier = Modifier
                            .fillMaxWidth()
                            .weight(1f, fill = false)
                    ) {
                        items(filteredPlaylist, key = { it.value.id }) { indexedEp ->
                            val isSelected = indexedEp.index == state.currentEpisodeIndex ||
                                    indexedEp.value.id == state.currentEpisode?.id

                            EpisodeOptionCard(
                                indexedEpisode = indexedEp,
                                isSelected = isSelected,
                                onClick = {
                                    onEvent(PlayerUiEvent.SelectEpisode(indexedEp.index))
                                    onEvent(PlayerUiEvent.SetActiveModal(null))
                                }
                            )
                        }
                    }
                }
            }
        }
    )
}

@Composable
private fun EpisodeOptionCard(
    indexedEpisode: IndexedValue<PlayerEpisode>,
    isSelected: Boolean,
    onClick: () -> Unit,
    modifier: Modifier = Modifier
) {
    val (originalIndex, ep) = indexedEpisode
    val episodeWord = stringResource(Res.string.episode)
    val seasonShort = stringResource(Res.string.season_short)
    val episodeShort = stringResource(Res.string.episode_short)

    val episodeTitle = ep.name ?: "$episodeWord ${ep.episodeNumber ?: (originalIndex + 1)}"
    val subtitle = resolveEpisodeSubtitle(ep, seasonShort, episodeShort)

    SelectableOptionCard(
        isSelected = isSelected,
        title = episodeTitle,
        subtitle = subtitle.takeIf { it.isNotBlank() },
        leadingContent = if (isSelected) {
            {
                MediaBadge(
                    text = stringResource(Res.string.playing),
                    backgroundColor = CloudStreamColors.Primary,
                    textColor = CloudStreamColors.OnMediaScrim
                )
            }
        } else null,
        onClick = onClick,
        modifier = modifier
    )
}

